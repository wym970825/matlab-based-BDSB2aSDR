function [m,w]=frontendMetric(t,name,valid,count)
    m=NaN; w=NaN;
    if ~isfield(t,name)||numel(t.(name))~=numel(valid), return; end
    v=double(t.(name)(:));
    ok=valid&isfinite(v)&v>=0&v<=1&isfinite(count)&count>0;
    if ~any(ok), return; end
    m=median(v(ok)); w=sum(v(ok).*count(ok))/sum(count(ok));
end
