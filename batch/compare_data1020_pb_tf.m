        'p95HorizontalDisagreementM',delta.horizontalP95M, ...
        'medianAbsoluteHeightDisagreementM',delta.absoluteHeightMedianM, ...
        'p95AbsoluteHeightDisagreementM',delta.absoluteHeightP95M);
    pair=struct('summary',summary,'pbNavigation',pb.navStats, ...
        'tfNavigation',tf.navStats,'positionDisagreement',delta, ...
        'pbPath',pb.path,'tfPath',tf.path);
end

function r=navigationStats(nav,trk)
    if isempty(nav), nav=struct; end
    lat=double(fieldOr(nav,{'latitude'},[]));
    lon=double(fieldOr(nav,{'longitude'},[]));
    h=double(fieldOr(nav,{'height'},[]));
    good=isfinite(lat)&isfinite(lon); hh=h(good&isfinite(h));
    rms=[]; passed=0;
    if isfield(nav,'raim')
        rms=fieldOr(nav.raim,{'residualRms'},[]);
        passed=nnz(fieldOr(nav.raim,{'passed'},[]));
    end
    r=struct('totalEpochs',numel(lat),'finiteEpochs',nnz(good), ...
        'raimPassedEpochs',passed,'plottedEpochs',trk.n, ...
        'removedJumpEpochs',trk.nRemovedJump,'heightMinM',minFinite(hh), ...
        'heightMedianM',medianFinite(hh),'heightMaxM',maxFinite(hh), ...
        'heightP01M',percentile(hh,1),'heightP99M',percentile(hh,99), ...
        'absHeightOver1000m',nnz(abs(hh)>1000), ...
        'absHeightOver10000m',nnz(abs(hh)>10000), ...
        'raimResidualRmsMedianM',medianFinite(rms), ...
        'raimResidualRmsP95M',percentile(rms,95));
end

function r=positionDisagreement(pb,tf)
    r=struct('matchedEpochs',0,'horizontalMedianM',NaN,'horizontalP95M',NaN, ...
        'horizontalMaxM',NaN,'absoluteHeightMedianM',NaN,'absoluteHeightP95M',NaN, ...
        'note','PB-vs-TF disagreement on filtered positions at matching source times; not positioning accuracy.');
    a=pb.navTrack; b=tf.navTrack;
    if a.n<2||b.n<2, return; end
    ta=double(pb.nav.currMeasSample(a.idx)).'/double(pb.settings.samplingFreq);
    tb=double(tf.nav.currMeasSample(b.idx)).'/double(tf.settings.samplingFreq);
    ta=ta(:); tb=tb(:);
    [tb,ix]=unique(tb,'stable');
    if ~issorted(tb)||numel(tb)<2, return; end
    latB=interp1(tb,b.lat(ix),ta,'linear',NaN);
    lonB=interp1(tb,b.lon(ix),ta,'linear',NaN);
    hB=interp1(tb,b.h(ix),ta,'linear',NaN);
    gapValid=false(size(ta)); maxGap=1.01*double(tf.settings.navSolPeriod)/1000;
    for j=1:numel(tb)-1
        if tb(j+1)-tb(j)<=maxGap
            gapValid=gapValid|(ta>=tb(j)&ta<=tb(j+1));
        end
    end
    ok=gapValid&isfinite(latB)&isfinite(lonB)&isfinite(hB)&isfinite(a.h);
    latA=a.lat(ok)*pi/180; latB=latB(ok)*pi/180;
    dlat=latB-latA; dlon=(lonB(ok)-a.lon(ok))*pi/180;
    v=sin(dlat/2).^2+cos(latA).*cos(latB).*sin(dlon/2).^2;
    dist=2*6371008.8*atan2(sqrt(max(0,v)),sqrt(max(0,1-v)));
    dh=abs(hB(ok)-a.h(ok));
    r.matchedEpochs=nnz(ok); r.horizontalMedianM=medianFinite(dist);
    r.horizontalP95M=percentile(dist,95); r.horizontalMaxM=maxFinite(dist);
    r.absoluteHeightMedianM=medianFinite(dh); r.absoluteHeightP95M=percentile(dh,95);
end

function sets=intervalsFromTicks(start,stop,mask,tol)
    sets=zeros(0,2); active=false; a=NaN; b=NaN;
    for j=1:numel(start)
        if ~mask(j)
            if active, sets(end+1,:)=[a b]; end %#ok<AGROW>
            active=false; continue
        end
        if active && abs(start(j)-b)<=tol
            b=stop(j);
        else
            if active, sets(end+1,:)=[a b]; end %#ok<AGROW>
            a=start(j); b=stop(j); active=true;
        end
    end
    if active, sets(end+1,:)=[a b]; end
end

function out=intersectIntervals(a,b)
    out=zeros(0,2);
    for i=1:size(a,1)
        for j=1:size(b,1)
            x=max(a(i,1),b(j,1)); y=min(a(i,2),b(j,2));
            if y>x, out(end+1,:)=[x y]; end %#ok<AGROW>
        end
    end
    % Input sets may contain independent segments after receiver rewinds.
    % Do not merge touching tracking segments: the discontinuity matters.
    if ~isempty(out), out=sortrows(out,1); end
end

function out=mergeIntervals(v,tol)
    out=zeros(0,2); if isempty(v), return; end
    v=sortrows(v,1); out=v(1,:);
    for i=2:size(v,1)
        if v(i,1)<=out(end,2)+tol
            out(end,2)=max(out(end,2),v(i,2));
        else
            out(end+1,:)=v(i,:); %#ok<AGROW>
        end
    end
end

function n=longest(v)
    if isempty(v), n=0; else, n=max(v(:,2)-v(:,1)); end
end

function v=longestInterval(a)
    v=[NaN NaN];
    if ~isempty(a), [~,i]=max(a(:,2)-a(:,1)); v=a(i,:); end
end

function [a,b]=commonCno(da,db,v)
    a=medianFinite(da.cno(da.cnoTime>=v(1)&da.cnoTime<=v(2)));
    b=medianFinite(db.cno(db.cnoTime>=v(1)&db.cnoTime<=v(2)));
end

function utc=firstNmeaUtc(path)
    utc=''; if ~isfile(path), return; end
    content=fileread(path);
    z=regexp(content,'\$[A-Z]{2}ZDA,(\d{6}(?:\.\d+)?),(\d{2}),(\d{2}),(\d{4}),','tokens','once');
    if isempty(z), return; end
    t=z{1}; utc=sprintf('%s-%s-%s %s:%s:%s UTC',z{4},z{3},z{2},t(1:2),t(3:4),t(5:end));
end

