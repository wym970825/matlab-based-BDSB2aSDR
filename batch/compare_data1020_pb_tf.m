    for prn=ids
        a=pb.trackRows([pb.trackRows.PRN]==prn);
        b=tf.trackRows([tf.trackRows.PRN]==prn);
        da=pb.details([pb.details.PRN]==prn); db=tf.details([tf.details.PRN]==prn);
        common=intersectIntervals(da.noReacq,db.noReacq);
        long=intersectIntervals(da.longState,db.longState);
        high=intersectIntervals(da.highElevation,db.highElevation);
        longHigh=intersectIntervals(da.longHighElevation,db.longHighElevation);
        best=longestInterval(high);
        [pa,pbC]=commonCno(da,db,best);
        r=struct('experimentNumber',e.experimentNumber,'sourceId',e.sourceId, ...
            'stationName',e.stationName,'PRN',prn, ...
            'pbLongestNoReacqSeconds',a.longestNoReacqSeconds, ...
            'tfLongestNoReacqSeconds',b.longestNoReacqSeconds, ...
            'pbLongestLongStateSeconds',a.longestLongStateSeconds, ...
            'tfLongestLongStateSeconds',b.longestLongStateSeconds, ...
            'pbLongestHighElevationSeconds',a.longestNoReacqAbove30Seconds, ...
            'tfLongestHighElevationSeconds',b.longestNoReacqAbove30Seconds, ...
