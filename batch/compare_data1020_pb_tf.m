function report = compare_data1020_pb_tf(manifestPath, outputDir)
%COMPARE_DATA1020_PB_TF Audit paired receiver runs without rerunning tracking.
% manifest.entries: experimentNumber, sourceId, stationName, pbDir, tfDir.
% Output times are seconds from the beginning of the source IQ file. The
% strict lists require a continuous physical interval, not 180000 records.
% Call compare_data1020_pb_tf('selftest') for small interval-math checks.
    if nargin >= 1 && strcmp(char(manifestPath),'selftest')
        selftest(); report=struct('ok',true); return
    end
    projectRoot=fileparts(fileparts(mfilename('fullpath')));
    addpath(projectRoot); setupPaths;
    manifest=jsondecode(fileread(manifestPath));
    if nargin<2 || isempty(outputDir)
        outputDir=fullfile(fileparts(manifestPath),'comparison');
    end
    if ~isfolder(outputDir), mkdir(outputDir); end
    entries=manifest.entries;
    summaries=struct([]); trackRows=struct([]); intervalRows=struct([]);
    commonRows=struct([]); pairDetails=struct([]);
    for k=1:numel(entries)
        e=normalizeEntry(entries(k),k);
        fprintf('COMPARE %02d %s\n',e.experimentNumber,e.sourceId);
        pb=readRun(e.pbDir,e,'PB'); tf=readRun(e.tfDir,e,'TF');
        trackRows=appendStruct(trackRows,pb.trackRows);
        trackRows=appendStruct(trackRows,tf.trackRows);
        intervalRows=appendStruct(intervalRows,pb.intervalRows);
        intervalRows=appendStruct(intervalRows,tf.intervalRows);
        [common,pair]=compareRuns(pb,tf,e);
        commonRows=appendStruct(commonRows,common);
        pairDetails=appendStruct(pairDetails,pair);
        summaries=appendStruct(summaries,pair.summary);
    end
    report=struct('generatedUtc',char(datetime('now','TimeZone','UTC', ...
        'Format',"yyyy-MM-dd'T'HH:mm:ss'Z'")), ...
        'manifestPath',char(manifestPath),'definitions',definitions(), ...
        'experiments',pairDetails,'satelliteMetrics',trackRows, ...
        'continuousIntervals',intervalRows,'pairedSatellites',commonRows);
    writeJson(fullfile(outputDir,'comparison_report.json'),report);
    writeRows(fullfile(outputDir,'comparison_summary.csv'),summaries);
    writeRows(fullfile(outputDir,'satellite_tracking_metrics.csv'),trackRows);
    writeRows(fullfile(outputDir,'continuous_tracking_intervals.csv'),intervalRows);
    writeRows(fullfile(outputDir,'no_reacq_180s.csv'),trackRows, ...
        @(r) r.noReacq180);
    writeRows(fullfile(outputDir,'long_state_180s.csv'),trackRows, ...
        @(r) r.longState180);
    writeRows(fullfile(outputDir,'paired_satellites.csv'),commonRows);
    writeRows(fullfile(outputDir,'common_no_reacq_180s.csv'),commonRows, ...
        @(r) r.bothNoReacq180);
    writeRows(fullfile(outputDir,'common_high_elevation_180s.csv'),commonRows, ...
        @(r) r.bothHighElevation180);
    writeRows(fullfile(outputDir,'common_high_elevation_same_interval_180s.csv'), ...
        commonRows,@(r) r.commonHighElevation180);
    writeRows(fullfile(outputDir,'common_long_high_elevation_same_interval_180s.csv'), ...
        commonRows,@(r) r.commonLongHighElevation180);
    writeBrief(fullfile(outputDir,'comparison_brief.html'),report);
    fprintf('Comparison written: %s\n',outputDir);
end

function e=normalizeEntry(raw,k)
    e=struct('experimentNumber',fieldOr(raw, ...
        {'experimentNumber','experimentIndex','number','index'},k), ...
        'sourceId',char(fieldOr(raw,{'sourceId','id','sourceShort'},'')), ...
        'stationName',char(fieldOr(raw,{'stationName','station'},'')), ...
        'pbDir',char(fieldOr(raw,{'pbDir','pbPath'},'')), ...
        'tfDir',char(fieldOr(raw,{'tfDir','tfPath'},'')));
    assert(isfolder(e.pbDir),'Missing PB folder: %s',e.pbDir);
    assert(isfolder(e.tfDir),'Missing TF folder: %s',e.tfDir);
end

function run=readRun(path,e,mode)
    S=load(fullfile(path,'ui_results.mat'));
    if isfield(S,'results'), R=S.results; else, R=S; end
    settings=R.settings;
    if isfield(S,'settings'), settings=S.settings; end
    nav=R.navSolutions;
    trk=navTrackTimeOrder(nav,settings);
    run=struct('mode',mode,'path',path,'settings',settings,'nav',nav, ...
        'navTrack',trk,'trackRows',struct([]),'intervalRows',struct([]), ...
        'details',struct([]),'navStats',navigationStats(nav,trk), ...
        'firstValidUtc',firstNmeaUtc(fullfile(path,'pvt.nmea')));
    detected=acquisitionDetectedMask(R.acqResults);
    run.acquiredPrns=settings.acqSatelliteList(detected);
    files=dir(fullfile(path,'temp','Trk_Prn_*_final.mat'));
    for j=1:numel(files)
        file=fullfile(files(j).folder,files(j).name);
        T=load(file,'finalTRes'); t=T.finalTRes;
        [row,detail,intervals]=trackStats(t,settings,nav,trk,e,mode,file,path);
        run.trackRows=appendStruct(run.trackRows,row);
        run.details=appendStruct(run.details,detail);
        run.intervalRows=appendStruct(run.intervalRows,intervals);
    end
end

function [r,d,rows]=trackStats(t,s,nav,navTrack,e,mode,file,path)
    fs=double(s.samplingFreq);
    start=double(t.absoluteSample(:))/fs;
    state=double(t.trk_state(:)); n=numel(start);
    assert(numel(state)==n,'Mismatched state/sample lengths for PRN %d',t.PRN);
    % Prefer the saved IFSource logical count. The fallback uses precisely
    % the pre-correlation inputs to trackOneChannel's block-size rule.
    count=ceil((double(s.codeLength)-double(t.remCodePhase(:))) ...
        ./ (double(t.codeFreq(:))/fs));
    count(state==9)=round(fs*double(s.intTime));
    countSource='reconstructed pre-correlation block size';
    if isfield(t,'frontendSampleCount')&&numel(t.frontendSampleCount)==n
        measured=double(t.frontendSampleCount(:));
        known=isfinite(measured)&measured>0;
        count(known)=measured(known);
        if all(known), countSource='saved frontendSampleCount';
        else, countSource='saved frontendSampleCount with reconstructed fallback'; end
    end
    stop=start+count/fs;
    valid=isfinite(start)&isfinite(stop)&count>0& ...
        count<2*fs*double(s.intTime)&isfinite(double(t.I_P(:)))& ...
        isfinite(double(t.Q_P(:)));
    if isfield(t,'frontendValidCount')&&numel(t.frontendValidCount)==n
        observed=double(t.frontendValidCount(:));
        valid=valid&(~isfinite(observed)|observed==count);
    end
    normal=valid&ismember(state,[1 2 3 4]);
    long=valid&ismember(state,[3 4]);
    tol=2/fs;
    noReacq=intervalsFromTicks(start,stop,normal,tol);
    longIntervals=intervalsFromTicks(start,stop,long,tol);
    [elevIntervals,elevTimes,elevValues,elevQualityCount]= ...
        elevationIntervals(nav,navTrack,t.PRN,s);
    high=intersectIntervals(noReacq,elevIntervals);
    longHigh=intersectIntervals(longIntervals,elevIntervals);
    cno=double(t.B2a_CNo(:)); ci=(1:numel(cno))'*double(s.CNoInterval);
    ci=min(n,max(1,ci)); cnoTime=stop(ci);
    cnoValid=isfinite(cno)&cno>0;
    cno=cno(cnoValid); cnoTime=cnoTime(cnoValid);
    goodElev=elevValues(isfinite(elevValues));
    eta=double(t.eta(:)); eta=eta(isfinite(eta)&eta>=0&eta<=1);
    % eta is the legacy whole-band PB zeroing fraction. TF v1 instead saves
    % its detector mask and tapered notch-application weights separately.
    if ~strcmp(mode,'PB'), eta=[]; end
    [detectorMedian,detectorMean]=frontendMetric(t,'frontendDetectorDuty',valid,count);
    [weightMedian,weightMean]=frontendMetric(t,'frontendMeanWeight',valid,count);
    [squaredMedian,squaredMean]=frontendMetric(t,'frontendMeanWeightSquared',valid,count);
    [supportMedian,supportMean]=frontendMetric(t,'frontendWeightSupportFraction',valid,count);
    reacq=state==9;
    r=struct('experimentNumber',e.experimentNumber,'sourceId',e.sourceId, ...
        'stationName',e.stationName,'mode',mode,'PRN',double(t.PRN), ...
        'recordCount',n,'requestedRecordCount',double(s.msToProcess), ...
        'fullLengthRecorded',n>=double(s.msToProcess), ...
        'blockCountSource',countSource,'fileStartSeconds',minFinite(start), ...
        'fileEndSeconds',maxFinite(stop), ...
        'recordedSpanSeconds',maxFinite(stop)-minFinite(start), ...
        'recordedSamplesSeconds',sum(count(valid))/fs, ...
        'reacqEpisodes',nnz(diff([false;reacq])==1), ...
        'reacqRecordedSeconds',sum(count(reacq&valid))/fs, ...
        'nonmonotonicOrGapTransitions',nnz(abs(start(2:end)-stop(1:end-1))>tol), ...
        'longestNoReacqSeconds',longest(noReacq), ...
        'longestLongStateSeconds',longest(longIntervals), ...
        'longestNoReacqAbove30Seconds',longest(high), ...
        'longestLongStateAbove30Seconds',longest(longHigh), ...
        'noReacq180',longest(noReacq)>=180, ...
        'longState180',longest(longIntervals)>=180, ...
        'noReacqAbove30For180',longest(high)>=180, ...
        'longStateAbove30For180',longest(longHigh)>=180, ...
        'medianB2aCnoDbHz',medianFinite(cno), ...
        'p10B2aCnoDbHz',percentile(cno,10), ...
        'p90B2aCnoDbHz',percentile(cno,90), ...
        'medianPbBlankingFraction',medianFinite(eta), ...
        'pbBlankingFractionValidEpochs',numel(eta), ...
        'medianFrontendDetectorDuty',detectorMedian, ...
        'medianFrontendMeanWeight',weightMedian, ...
        'medianFrontendMeanWeightSquared',squaredMedian, ...
        'medianFrontendWeightSupportFraction',supportMedian, ...
        'sampleWeightedFrontendDetectorDuty',detectorMean, ...
        'sampleWeightedFrontendMeanWeight',weightMean, ...
        'sampleWeightedFrontendMeanWeightSquared',squaredMean, ...
        'sampleWeightedFrontendWeightSupportFraction',supportMean, ...
        'elevationValidEpochs',numel(goodElev), ...
        'elevationAcceptedEpochs',elevQualityCount, ...
        'elevationMinDeg',minFinite(goodElev), ...
        'elevationMedianDeg',medianFinite(goodElev), ...
        'elevationMaxDeg',maxFinite(goodElev), ...
        'trackingMat',file,'trackingFigure',fullfile(path,'figures', ...
            'trkResult',sprintf('PRN_%02d_tracking.png',t.PRN)));
    d=struct('PRN',double(t.PRN),'noReacq',noReacq,'longState',longIntervals, ...
        'highElevation',high,'longHighElevation',longHigh, ...
        'cno',cno,'cnoTime',cnoTime,'elevationTime',elevTimes, ...
        'elevation',elevValues);
    rows=struct([]);
    names={'no_reacq','long_state','no_reacq_above_30','long_state_above_30'};
    sets={noReacq,longIntervals,high,longHigh};
    for a=1:numel(sets)
        v=sets{a};
        for b=1:size(v,1)
            z=struct('experimentNumber',e.experimentNumber,'sourceId',e.sourceId, ...
                'stationName',e.stationName,'mode',mode,'PRN',double(t.PRN), ...
                'criterion',names{a},'fileStartSeconds',v(b,1), ...
                'fileEndSeconds',v(b,2),'durationSeconds',v(b,2)-v(b,1), ...
                'atLeast180Seconds',v(b,2)-v(b,1)>=180);
            rows=appendStruct(rows,z);
        end
    end
end

function [intervals,times,values,nAccepted]=elevationIntervals(nav,track,prn,s)
    intervals=zeros(0,2); times=[]; values=[]; nAccepted=0;
    if isempty(nav)||~all(isfield(nav,{'currMeasSample','el','PRN'})), return; end
    n=min([numel(nav.currMeasSample),size(nav.el,2),size(nav.PRN,2)]);
    times=double(nav.currMeasSample(1:n)).'/double(s.samplingFreq);
    values=nan(n,1);
    for j=1:n
        % postNavigation writes PRN(activeChnList,epoch) by original channel
        % slot, so PRN grows only through the highest used slot. In contrast
        % el(:,epoch) is prefilled to nChUse (63 in these experiments). The
        % row numbers match, but the matrices need not have equal heights.
        idx=find(double(nav.PRN(:,j))==prn);
        assert(numel(idx)<=1,'Duplicate PRN %d at navigation epoch %d',prn,j);
        if ~isempty(idx)
            assert(idx<=size(nav.el,1), ...
                'PRN %d channel slot %d has no elevation row at epoch %d',prn,idx,j);
            if isfinite(nav.el(idx,j)), values(j)=double(nav.el(idx,j)); end
        end
    end
    accepted=false(n,1); ix=track.idx(track.idx<=n); accepted(ix)=true;
    if isfield(nav,'raim')&&isfield(nav.raim,'passed')
        q=false(n,1); p=logical(nav.raim.passed(:));
        q(1:min(n,numel(p)))=p(1:min(n,numel(p)));
        accepted=accepted&q;
    end
    accepted=accepted&isfinite(values)&isfinite(times)&times>=0;
    nAccepted=nnz(accepted);
    % No extrapolation, and never bridge a missing/rejected nav epoch.
    high=accepted&values>30;
    step=double(s.navSolPeriod)/1000;
    for j=1:n-1
        if high(j)&&high(j+1)&&times(j+1)>times(j)&& ...
                times(j+1)-times(j)<=step*1.01
            intervals(end+1,:)=[times(j),times(j+1)]; %#ok<AGROW>
        end
    end
    intervals=mergeIntervals(intervals,2/double(s.samplingFreq));
end

function [rows,pair]=compareRuns(pb,tf,e)
