function s=esc(s)
    s=char(string(s)); s=strrep(s,'&','&amp;'); s=strrep(s,'<','&lt;');
    s=strrep(s,'>','&gt;'); s=strrep(s,'"','&quot;');
end
function href=relativeHref(target,htmlPath)
    a=strsplit(strrep(char(target),'\','/'),'/');
    b=strsplit(strrep(fileparts(char(htmlPath)),'\','/'),'/');
    common=0;
    while common<min(numel(a),numel(b))&&strcmpi(a{common+1},b{common+1})
        common=common+1;
    end
    assert(common>0,'HTML and linked artifact must share a path root.');
    parts=[repmat({'..'},1,numel(b)-common),a(common+1:end)];
    for i=1:numel(parts)
        bytes=unicode2native(parts{i},'UTF-8'); encoded='';
        for byte=reshape(bytes,1,[])
            if (byte>=65&&byte<=90)||(byte>=97&&byte<=122)|| ...
                    (byte>=48&&byte<=57)||ismember(byte,uint8('-._~'))
                encoded=[encoded char(byte)]; %#ok<AGROW>
            else
                encoded=[encoded sprintf('%%%02X',byte)]; %#ok<AGROW>
            end
        end
        parts{i}=encoded;
    end
    href=strjoin(parts,'/');
end
