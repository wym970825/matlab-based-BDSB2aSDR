            'pbMedianCnoDbHz',a.medianB2aCnoDbHz, ...
            'tfMedianCnoDbHz',b.medianB2aCnoDbHz, ...
            'deltaMedianCnoDbHz',b.medianB2aCnoDbHz-a.medianB2aCnoDbHz, ...
            'pbMedianFrontendDetectorDuty',a.medianFrontendDetectorDuty, ...
            'tfMedianFrontendDetectorDuty',b.medianFrontendDetectorDuty, ...
            'pbMedianFrontendMeanWeight',a.medianFrontendMeanWeight, ...
            'tfMedianFrontendMeanWeight',b.medianFrontendMeanWeight, ...
            'pbMedianFrontendMeanWeightSquared',a.medianFrontendMeanWeightSquared, ...
            'tfMedianFrontendMeanWeightSquared',b.medianFrontendMeanWeightSquared, ...
            'pbMedianFrontendWeightSupportFraction',a.medianFrontendWeightSupportFraction, ...
            'tfMedianFrontendWeightSupportFraction',b.medianFrontendWeightSupportFraction, ...
            'pbElevationMinDeg',a.elevationMinDeg, ...
            'tfElevationMinDeg',b.elevationMinDeg, ...
            'pbElevationMedianDeg',a.elevationMedianDeg, ...
            'tfElevationMedianDeg',b.elevationMedianDeg, ...
            'bothNoReacq180',a.noReacq180&&b.noReacq180, ...
            'bothLongState180',a.longState180&&b.longState180, ...
            'bothHighElevation180',a.noReacqAbove30For180&&b.noReacqAbove30For180, ...
            'bothLongHighElevation180',a.longStateAbove30For180&&b.longStateAbove30For180, ...
            'commonNoReacqSeconds',longest(common), ...
            'commonLongStateSeconds',longest(long), ...
            'commonHighElevationSeconds',longest(high), ...
            'commonLongHighElevationSeconds',longest(longHigh), ...
            'commonNoReacq180',longest(common)>=180, ...
            'commonLongState180',longest(long)>=180, ...
            'commonHighElevation180',longest(high)>=180, ...
            'commonLongHighElevation180',longest(longHigh)>=180, ...
            'commonHighElevationStartSeconds',best(1), ...
            'commonHighElevationEndSeconds',best(2), ...
            'pbCommonHighElevationMedianCnoDbHz',pa, ...
            'tfCommonHighElevationMedianCnoDbHz',pbC, ...
            'deltaCommonHighElevationMedianCnoDbHz',pbC-pa, ...
            'pbTrackingMat',a.trackingMat,'tfTrackingMat',b.trackingMat, ...
            'pbTrackingFigure',a.trackingFigure,'tfTrackingFigure',b.trackingFigure);
        rows=appendStruct(rows,r);
    end
    delta=positionDisagreement(pb,tf);
    summary=struct('experimentNumber',e.experimentNumber,'sourceId',e.sourceId, ...
        'stationName',e.stationName,'pbFirstValidUtc',pb.firstValidUtc, ...
        'tfFirstValidUtc',tf.firstValidUtc, ...
        'pbAcquired',numel(pb.acquiredPrns),'tfAcquired',numel(tf.acquiredPrns), ...
        'pbAcquiredPrns',joinPrns(pb.acquiredPrns), ...
        'tfAcquiredPrns',joinPrns(tf.acquiredPrns), ...
        'pbFullLengthRecorded',nnz([pb.trackRows.fullLengthRecorded]), ...
        'tfFullLengthRecorded',nnz([tf.trackRows.fullLengthRecorded]), ...
        'pbFullLengthPrns',selectedPrns(pb.trackRows,'fullLengthRecorded'), ...
        'tfFullLengthPrns',selectedPrns(tf.trackRows,'fullLengthRecorded'), ...
        'pbRequestedSeconds',double(pb.settings.msToProcess)*double(pb.settings.intTime), ...
        'tfRequestedSeconds',double(tf.settings.msToProcess)*double(tf.settings.intTime), ...
        'pbMaxRecordedSpanSeconds',maxFinite([pb.trackRows.recordedSpanSeconds]), ...
        'tfMaxRecordedSpanSeconds',maxFinite([tf.trackRows.recordedSpanSeconds]), ...
        'pbNoReacq180Prns',selectedPrns(pb.trackRows,'noReacq180'), ...
        'tfNoReacq180Prns',selectedPrns(tf.trackRows,'noReacq180'), ...
