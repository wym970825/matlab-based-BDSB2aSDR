%DEBUG_PLOT_ACQ_CHANNEL Replay and plot saved acquisition channel results.
%
% Set these variables before calling RUN to select another result root or
% override replay options without editing this script:
%
%   acqReplayRoot = 'F:\path\to\batch_result';
%   acqReplayOptions = { ...
%       'RunNames', "0001_example", ...
%       'PRNs', [20 38], ...
%       'FontSize', 16, ...
%       'TitleFontSize', 19, ...
%       'Visible', true, ...
%       'Overwrite', false, ...
%       'SaveFigure', true, ...
%       'KeepLoadedResults', true};
%   run('tests/debug_plot_Acq_channel.m');
%
% Outputs in the caller workspace:
%   acqReplayReport - per-run source, PRN, figure, timing, and error data
%   acqReplayData   - acquisition structures when KeepLoadedResults is true

projectRoot = fileparts(fileparts(mfilename('fullpath')));
setupPaths();

if ~exist('acqReplayRoot', 'var') || isempty(acqReplayRoot)
    acqReplayRoot = fullfile(projectRoot, 'results', 'batch', ...
        '260802_X310_IFData_full');
end
if ~exist('acqReplayOptions', 'var') || isempty(acqReplayOptions)
    acqReplayOptions = {};
end
if ~iscell(acqReplayOptions)
    error('debug_plot_Acq_channel:OptionsType', ...
        'acqReplayOptions must be a cell array of name-value arguments.');
end

[acqReplayReport, acqReplayData] = replayAcquisitionChannels( ...
    acqReplayRoot, acqReplayOptions{:});

fprintf(['Acquisition replay complete: %d run(s), %d searched PRN(s), ' ...
    '%d acquired PRN(s), %d figure(s), %d error(s).\n'], ...
    acqReplayReport.nRuns, acqReplayReport.nSearched, ...
    acqReplayReport.nAcquired, acqReplayReport.nFigures, ...
    acqReplayReport.nErrors);
